async function seed() {
  console.log(`Seeding ${establishments.length} Maryland establishments...`);

  const { data, error } = await supabase
    .from('businesses')
    .insert(establishments)
    .select('id, name, category, city');

  if (error) {
    console.error('Seed error:', error.message);
    process.exit(1);
  }

  console.log(`Successfully seeded ${data.length} establishments:`);
  data.forEach((b) => {
    console.log(`  [${b.category}] ${b.name} — ${b.city}`);
  });
}

seed();
