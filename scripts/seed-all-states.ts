async function seed() {
  console.log(`Seeding ${establishments.length} establishments across all 50 states...`);

  const { data, error } = await supabase
    .from('businesses')
    .insert(establishments)
    .select('id, name, category, city, state');

  if (error) {
    console.error('Seed error:', error.message);
    process.exit(1);
  }

  console.log(`Successfully seeded ${data.length} establishments.`);
  const byState: Record<string, number> = {};
  data.forEach((b) => {
    byState[b.state] = (byState[b.state] || 0) + 1;
  });
  Object.keys(byState).sort().forEach((s) => {
    console.log(`  ${s}: ${byState[s]} entries`);
  });
}

